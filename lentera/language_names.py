def canonical(name: str) -> str:
    """Nama baku sebuah bahasa: spasi dirapikan dan ejaan lain disatukan."""
    clean = re.sub(r"\s+", " ", (name or "").strip())
    clean = re.sub(r"\s+language$", "", clean, flags=re.IGNORECASE)
    return ALIASES.get(clean.lower(), clean)


def indonesian(name: str) -> str:
    """Nama tampilan berbahasa Indonesia, misalnya "Spanish" -> "Bahasa Spanyol"."""
    base = canonical(name)
    return f"Bahasa {NAMES_ID.get(base, base)}"
